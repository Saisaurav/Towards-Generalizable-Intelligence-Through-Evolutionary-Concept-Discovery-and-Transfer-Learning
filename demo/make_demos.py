#!/usr/bin/env python3
"""Three CACHED demo grid games. Specs are hand-authored in the platform's own schema (NOT live LLM output); each is validated by the
platform's GameSpec (which enforces reachability) and written both as JSON and as the grid-spec text file consumed by the C++ trainer."""
import json, sys
sys.path.insert(0, '.')
from llm_game_platform.spec import GameSpec
DEMOS = [
 dict(id='demo_1_open_field', title='Open Field', description='Cross a small open field to the goal; two hazards sit near the direct path.', width=6, height=6, start=[0,0], goal=[5,5], walls=[], hazards=[[2,2],[3,3]], max_turns=40),
 dict(id='demo_2_wall_maze', title='Wall Maze', description='A wall with a single gap forces a detour to the goal.', width=7, height=6, start=[0,5], goal=[6,0], walls=[[3,0],[3,1],[3,2],[3,3],[3,4]], hazards=[[5,2]], max_turns=50),
 dict(id='demo_3_hazard_corridor', title='Hazard Corridor', description='A narrow corridor lined with hazards; the safe route zig-zags.', width=8, height=5, start=[0,2], goal=[7,2], walls=[[2,0],[2,1],[5,3]], hazards=[[3,2],[4,1],[4,2],[6,2],[1,1],[1,3]], max_turns=45),
]
out = []
for d in DEMOS:
    spec = GameSpec.from_mapping({k: v for k, v in d.items() if k != 'id'})
    lines = [f"{d['width']} {d['height']} {d['max_turns']} {d['start'][0]} {d['start'][1]} {d['goal'][0]} {d['goal'][1]}", str(len(d['walls'])), *(f"{x} {y}" for x, y in d['walls']), str(len(d['hazards'])), *(f"{x} {y}" for x, y in d['hazards'])]
    open(f"demo/{d['id']}.txt", 'w').write('\n'.join(lines) + '\n')
    out.append(dict(d, source='cached_hand_authored', note='Not generated by a live LLM call; validated by GameSpec.'))
json.dump(out, open('llm_game_platform/web/data/demo_games.json', 'w'), indent=1)
print('validated', len(out), 'demo specs')
